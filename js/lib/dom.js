// Minimal DOM helpers. The app is dependency free on purpose, so views build
// their markup with this small hyperscript instead of a framework.

/**
 * Create an element.
 *   h("div", { class: "panel" }, "text", h("span", {}, "child"))
 * Special props: `class`, `html` (raw HTML), `dataset`, `on<Event>` handlers,
 * and the boolean properties `checked`, `disabled`, `hidden`.
 */
export const h = (tag, props = {}, ...children) => {
  const el = document.createElement(tag);

  for (const [key, value] of Object.entries(props || {})) {
    if (value === null || value === undefined || value === false) continue;
    if (key === "class") el.className = value;
    else if (key === "html") el.innerHTML = value;
    else if (key === "dataset") Object.assign(el.dataset, value);
    else if (key.startsWith("on") && typeof value === "function") {
      el.addEventListener(key.slice(2).toLowerCase(), value);
    } else if (key === "checked" || key === "disabled" || key === "hidden") {
      el[key] = Boolean(value);
    } else {
      el.setAttribute(key, value);
    }
  }

  append(el, children);
  return el;
};

const append = (el, children) => {
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    if (Array.isArray(child)) append(el, child);
    else if (child instanceof Node) el.appendChild(child);
    else el.appendChild(document.createTextNode(String(child)));
  }
};

/** Replace every child of `node` with the given content. */
export const mount = (node, ...children) => {
  node.textContent = "";
  append(node, children);
  return node;
};

/** Pixel ornament from assets/pixel, generated by tools/gen-pixel-assets.mjs. */
export const glyph = (name, extraClass = "") => glyphImg(`assets/pixel/${name}.svg`, extraClass);

/**
 * Official brand ornament from assets/logo (see the note in that folder). It is
 * rendered as a CSS mask instead of an image so it takes `currentColor` and can
 * sit on the paper panels as well as on the dark ones.
 */
export const brandMark = (name, extraClass = "") =>
  h("span", { class: `mark mark--${name} ${extraClass}`.trim(), "aria-hidden": "true" });

const glyphImg = (src, extraClass) =>
  h("img", {
    class: `glyph ${extraClass}`.trim(),
    src,
    alt: "",
    "aria-hidden": "true",
    draggable: "false",
  });

/**
 * Decorative row of repeating ornaments, e.g. the butterfly dividers around a
 * panel title. Takes a pixel sprite name, a brand mark name, or a function of
 * the mark index when the row should alternate between designs.
 */
export const ornamentRow = (mark, count = 5, extraClass = "") => {
  const make =
    typeof mark === "function" ? mark : typeof mark === "string" ? () => glyph(mark) : () => mark;
  return h(
    "span",
    { class: `ornament ${extraClass}`.trim(), "aria-hidden": "true" },
    Array.from({ length: count }, (_, index) => make(index))
  );
};

/** Retro switch built from a checkbox so it stays keyboard accessible. */
export const switchEl = ({ checked, label, onChange }) => {
  const input = h("input", {
    type: "checkbox",
    class: "switch__input sr-only",
    checked,
    onchange: (event) => onChange(event.target.checked),
  });
  return h(
    "label",
    { class: "switch", title: label },
    input,
    h("span", { class: "switch__track" }, h("span", { class: "switch__knob" })),
    label ? h("span", { class: "sr-only" }, label) : null
  );
};

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

/** "2026-10-11" -> "11 October 2026" (kept dependency free). */
export const formatDate = (iso) => {
  if (!iso) return "";
  const [year, month, day] = iso.slice(0, 10).split("-");
  const name = MONTHS[Number(month) - 1] || month;
  return `${Number(day)} ${name} ${year}`;
};
